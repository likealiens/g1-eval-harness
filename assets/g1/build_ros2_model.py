"""G1 from the ROS 2 stack (unitree_description, BSD) with motors and a pelvis accelerometer."""

import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
UPSTREAM = os.path.join(HERE, "g1_ros2_upstream.xml")
OUTPUT = os.path.join(HERE, "g1_29dof_ros2.xml")
SENSORS = """  <sensor>
    <accelerometer name="imu-pelvis-linear-acceleration" site="imu_in_pelvis"/>
  </sensor>
"""


def build():
  with open(UPSTREAM) as f:
    xml = f.read()
  if "<actuator>" in xml:
    raise RuntimeError("upstream model already has actuators; review this script")
  xml = xml.replace('meshdir="../meshes/g1"', 'meshdir="meshes"', 1)
  xml = xml.replace('<mujoco model="g1">', '<mujoco model="g1_29dof_ros2">', 1)
  joints = re.findall(r'<joint name="([a-z_]+_joint)"', xml)
  if len(joints) != 29:
    raise RuntimeError(f"expected 29 joints, found {len(joints)}")
  motors = "".join(f'    <motor name="{j}" joint="{j}"/>\n' for j in joints)
  extra = f"  <actuator>\n{motors}  </actuator>\n\n{SENSORS}\n"
  xml = xml.replace("</mujoco>", extra + "</mujoco>", 1)
  header = "<!-- GENERATED by build_ros2_model.py from g1_ros2_upstream.xml; do not edit -->\n"
  with open(OUTPUT, "w") as f:
    f.write(header + xml)
  return OUTPUT


if __name__ == "__main__":
  print(f"wrote {build()}")
